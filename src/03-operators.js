// Operadores Aritmeticos

// Suma (+)
const suma = 5 + 3;
console.log(suma);


// Resta(-)
const resta = 5 - 3;
console.log(resta);


// Multiplicacion (*)
const multiplicacion = 5 * 3;
console.log(multiplicacion);


// Division (/)
const division = 5 * 3;
console.log(division);


// Modulo (%)
const modulo = 5 % 2;
console.log(modulo);


// Exponenciacion (**)
const potencia = 2 ** 5;
console.log(potencia);

// Operadores de Asignacion

// Asignacion con suma (+=)
let a = 5;
a += 3;
console.log(a);


// Asignacion con resta (-=)
let b = 10;
b -= 3;
console.log(b);

// Asignacion con Multiplicacion (*=)
let c = 6;
c *= 3;
console.log(c);

// Asignacion con divsion (/=)
let d = 15;
d /= 3;
console.log(d);

// Operadores de incremento y decremento
let contador = 10;

contador++;
console.log(contador);

contador--;
console.log(contador);

//  Infinity
console.log(1/0);

console.log(-1/0);  // -Infinity

// NaN (Not a Number)
console.log(0/0);
console.log('hola'*2);

