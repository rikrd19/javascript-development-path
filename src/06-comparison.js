// Operadores de comparacion en JS: Igualdad y Desigualdad

// Igualdad Debil (==)
console.log(5 == '5');  // true
console.log(true == 1); // true
console.log(false == 0); // true
console.log(null == undefined);  // true

// Desigualdad Debil (!=)
console.log(5 != '5');  // false


// Igualdad Estricta 
console.log(5 === 5);
console.log(5 === '5');

// Desigualdad estricta 
console.log(5 !== '5');  // true
console.log(5 !== 5);  // false
